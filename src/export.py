"""Report export module for Creator Analytics Copilot (PDF, Markdown, CSV)."""

import io
from typing import Dict, Any, List
import pandas as pd
from fpdf import FPDF


class CreatorReportPDF(FPDF):
    """Custom styled PDF generator for Creator Analytics Copilot."""

    def header(self):
        self.set_font("Helvetica", "B", 16)
        self.set_text_color(79, 70, 229)  # Indigo
        self.cell(0, 10, "Creator Analytics Copilot - Growth Report", border=False, new_x="LMARGIN", new_y="NEXT", align="L")
        self.set_font("Helvetica", "I", 9)
        self.set_text_color(107, 114, 128)  # Muted grey
        self.cell(0, 6, "Submitted by Bhuvanashree K R | Problem Statement 24", border=False, new_x="LMARGIN", new_y="NEXT", align="L")
        self.ln(4)
        self.set_draw_color(229, 231, 235)
        self.line(self.get_x(), self.get_y(), self.get_x() + 190, self.get_y())
        self.ln(6)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(156, 163, 175)
        self.cell(0, 10, f"Page {self.page_no()}/{{nb}} | Strictly Confidential - Creator Session Export", align="C")


def generate_markdown_report(
    kpis: Dict[str, Any],
    ai_results: Dict[str, Any],
    platform: str = "Creator Channel",
) -> str:
    """Generates a comprehensive Markdown report."""
    md = []
    md.append("# 🚀 Creator Analytics Copilot — Executive Report")
    md.append(f"**Platform:** {platform}  \n**Generated for:** Bhuvanashree K R (Problem 24)  \n")
    md.append("---")
    
    # 1. KPIs
    md.append("\n## 📊 Channel Performance Baseline")
    md.append(f"- **Total Content Pieces:** {kpis.get('total_posts', 0):,}")
    md.append(f"- **Total Lifetime Views:** {kpis.get('total_views', 0):,}")
    md.append(f"- **Median Views per Post:** {kpis.get('median_views', 0):,.0f}")
    md.append(f"- **Top 10% View Average:** {kpis.get('top_10_mean_views', 0):,.0f} (+{kpis.get('views_lift_vs_median_pct', 0):.0f}% vs median)")
    md.append(f"- **Average Engagement Rate:** {kpis.get('mean_engagement_rate', 0):.2f}%")
    if kpis.get("total_watch_hours"):
        md.append(f"- **Total Watch Time:** {kpis.get('total_watch_hours', 0):,.1f} hours")
    if kpis.get("mean_ctr"):
        md.append(f"- **Average CTR:** {kpis.get('mean_ctr', 0):.2f}%")

    # 2. What Worked
    md.append("\n## 🏆 What Worked (Winning Patterns)")
    for item in ai_results.get("what_worked", []):
        caveat_str = f" *({item['caveat']})*" if item.get("caveat") else ""
        md.append(f"- **{item['statement']}**  \n  `Confidence: {item['confidence']}` | `Sample Size: {item['sample_size']} posts`{caveat_str}")

    # 3. What Didn't Work
    md.append("\n## ⚠️ What Didn't Work (Underperforming Patterns)")
    for item in ai_results.get("what_didnt", []):
        caveat_str = f" *({item['caveat']})*" if item.get("caveat") else ""
        md.append(f"- **{item['statement']}**  \n  `Confidence: {item['confidence']}` | `Sample Size: {item['sample_size']} posts`{caveat_str}")

    # 4. Why It Worked (Hypotheses)
    md.append("\n## 💡 Why It Worked (Algorithmic & Psychological Hypotheses)")
    for hyp in ai_results.get("why_hypotheses", []):
        md.append(f"### [Hypothesis] {hyp['topic']}")
        md.append(f"{hyp['hypothesis']}\n")

    # 5. Next 10 Ideas
    md.append("\n## 🚀 Next 10 Content Ideas (Data-Backed)")
    for i, idea in enumerate(ai_results.get("next_10_ideas", []), 1):
        md.append(f"### {i}. {idea['title']}")
        md.append(f"- **3-Second Hook:** \"{idea['hook']}\"")
        md.append(f"- **Format:** `{idea['format']}`")
        md.append(f"- **Best Posting Slot:** `{idea['best_posting_slot']}`")
        md.append(f"- **Data-Backed Reason:** {idea['data_backed_reason']}\n")

    md.append("---")
    md.append("Generated by **Creator Analytics Copilot** (Autonomous AI Data Engine)")
    return "\n".join(md)


def generate_ideas_csv(ideas: List[Dict[str, Any]]) -> str:
    """Exports content ideas to CSV format."""
    df = pd.DataFrame(ideas)
    return df.to_csv(index=False)


def generate_pdf_report(
    kpis: Dict[str, Any],
    ai_results: Dict[str, Any],
    platform: str = "Creator Channel",
) -> bytes:
    """Generates an executive PDF report using fpdf2."""
    pdf = CreatorReportPDF(orientation="P", unit="mm", format="A4")
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()

    # Section 1: KPIs
    pdf.set_font("Helvetica", "B", 13)
    pdf.set_text_color(17, 24, 39)
    pdf.cell(0, 8, "1. Executive Performance Baseline", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(55, 65, 81)

    kpi_lines = [
        f"Platform: {platform}",
        f"Total Analyzed Posts: {kpis.get('total_posts', 0):,}",
        f"Total Views: {kpis.get('total_views', 0):,}",
        f"Median Views: {kpis.get('median_views', 0):,.0f} (Top 10% avg: {kpis.get('top_10_mean_views', 0):,.0f}, +{kpis.get('views_lift_vs_median_pct', 0):.0f}% lift)",
        f"Mean Engagement Rate: {kpis.get('mean_engagement_rate', 0):.2f}%",
    ]
    if kpis.get("total_watch_hours"):
        kpi_lines.append(f"Total Watch Time: {kpis.get('total_watch_hours', 0):,.1f} hours")
    if kpis.get("mean_ctr"):
        kpi_lines.append(f"Average Click-Through Rate: {kpis.get('mean_ctr', 0):.2f}%")

    for line in kpi_lines:
        pdf.cell(0, 6, f"  * {line}", new_x="LMARGIN", new_y="NEXT")

    pdf.ln(4)

    # Section 2: What Worked
    pdf.set_font("Helvetica", "B", 13)
    pdf.set_text_color(17, 24, 39)
    pdf.cell(0, 8, "2. Key Winning Patterns (What Worked)", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 9.5)
    pdf.set_text_color(55, 65, 81)

    for item in ai_results.get("what_worked", []):
        clean_stmt = item["statement"].encode("latin-1", "replace").decode("latin-1")
        pdf.multi_cell(0, 5, f"[+] {clean_stmt} (Confidence: {item['confidence']}, N={item['sample_size']})")
        pdf.ln(1)

    pdf.ln(4)

    # Section 3: What Didn't Work
    pdf.set_font("Helvetica", "B", 13)
    pdf.set_text_color(17, 24, 39)
    pdf.cell(0, 8, "3. Underperforming Outliers (What Didn't Work)", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 9.5)
    pdf.set_text_color(55, 65, 81)

    for item in ai_results.get("what_didnt", []):
        clean_stmt = item["statement"].encode("latin-1", "replace").decode("latin-1")
        pdf.multi_cell(0, 5, f"[-] {clean_stmt} (Confidence: {item['confidence']}, N={item['sample_size']})")
        pdf.ln(1)

    pdf.ln(4)

    # Section 4: Hypotheses
    pdf.set_font("Helvetica", "B", 13)
    pdf.set_text_color(17, 24, 39)
    pdf.cell(0, 8, "4. Algorithmic & Psychological Hypotheses (Why)", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 9.5)
    pdf.set_text_color(55, 65, 81)

    for hyp in ai_results.get("why_hypotheses", []):
        topic = hyp["topic"].encode("latin-1", "replace").decode("latin-1")
        text = hyp["hypothesis"].encode("latin-1", "replace").decode("latin-1")
        pdf.set_font("Helvetica", "B", 9.5)
        pdf.cell(0, 6, f"[Hypothesis] {topic}:", new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", "", 9.5)
        pdf.multi_cell(0, 5, text)
        pdf.ln(2)

    pdf.ln(4)

    # Section 5: Next 10 Ideas
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 13)
    pdf.set_text_color(17, 24, 39)
    pdf.cell(0, 8, "5. Data-Backed Next 10 Content Ideas", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(55, 65, 81)

    for i, idea in enumerate(ai_results.get("next_10_ideas", []), 1):
        title = idea["title"].encode("latin-1", "replace").decode("latin-1")
        hook = idea["hook"].encode("latin-1", "replace").decode("latin-1")
        fmt = idea["format"].encode("latin-1", "replace").decode("latin-1")
        slot = idea["best_posting_slot"].encode("latin-1", "replace").decode("latin-1")
        reason = idea["data_backed_reason"].encode("latin-1", "replace").decode("latin-1")

        pdf.set_font("Helvetica", "B", 10)
        pdf.set_text_color(79, 70, 229)
        pdf.cell(0, 6, f"{i}. {title}", new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", "", 9)
        pdf.set_text_color(55, 65, 81)
        pdf.multi_cell(0, 5, f"   Hook: \"{hook}\" | Format: {fmt} | Slot: {slot}\n   Reason: {reason}")
        pdf.ln(2)

    return bytes(pdf.output())
